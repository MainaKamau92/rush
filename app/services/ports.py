from datetime import datetime
from pathlib import Path
from typing import Protocol

from app.models.github import Acceptance, FindingEvent
from app.schemas.github import JobStatus, ReviewJob
from app.schemas.learning import LearningProposal
from app.schemas.policy import Rule
from app.schemas.review import ReviewRecord


class StateRepository(Protocol):
    async def open(self) -> None: ...
    async def close(self) -> None: ...
    async def schema_version(self) -> int: ...
    async def migrate(self) -> int: ...
    async def backup(self, destination: Path) -> None: ...


class ReviewRepository(Protocol):
    async def create(self, record: ReviewRecord) -> None: ...
    async def get(self, run_id: str) -> ReviewRecord: ...
    async def save(self, record: ReviewRecord, expected_revision: int) -> None: ...


class JobRepository(Protocol):
    async def accept(
        self,
        delivery_id: str,
        payload_sha256: str,
        event: str,
        job: ReviewJob | None,
        at: datetime,
    ) -> Acceptance: ...
    async def claim(self, at: datetime) -> ReviewJob | None: ...
    async def note(self, job_id: str, reason: str, at: datetime) -> None: ...
    async def finish(
        self, job_id: str, status: JobStatus, reason: str, at: datetime
    ) -> None: ...
    async def recover(
        self, at: datetime, max_attempts: int
    ) -> tuple[ReviewJob, ...]: ...
    async def get(self, job_id: str) -> ReviewJob: ...
    async def recent(self, limit: int) -> tuple[ReviewJob, ...]: ...


class FindingEventRepository(Protocol):
    async def record(self, event: FindingEvent) -> None: ...
    async def history(
        self, repository: str, pull_request: int, identity: str
    ) -> tuple[FindingEvent, ...]: ...


class PublicationRepository(Protocol):
    async def find(self, comment_id: int) -> tuple[str, str] | None: ...
    async def plan(self, run_id: str, item: str, kind: str, at: datetime) -> None: ...
    async def settle(
        self,
        run_id: str,
        item: str,
        status: str,
        comment_id: int | None,
        detail: str | None,
        at: datetime,
    ) -> None: ...


class LearningRepository(Protocol):
    async def save(
        self,
        proposal: LearningProposal,
        previous: LearningProposal | None = None,
        rule: Rule | None = None,
    ) -> None: ...
    async def get(self, proposal_id: str) -> LearningProposal | None: ...
    async def proposals(self) -> tuple[LearningProposal, ...]: ...
    async def rules(self) -> tuple[Rule, ...]: ...
